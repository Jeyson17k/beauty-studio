-- Cambios del modelo para bases que ya existían (se puede ejecutar varias veces sin problema).
-- Los aplica `npm run db:crear` cuando las tablas ya están creadas.

-- Correo de recuperación de la administradora
ALTER TABLE usuario_admin ADD COLUMN IF NOT EXISTS correo VARCHAR(120);
ALTER TABLE usuario_admin ADD COLUMN IF NOT EXISTS clave_emergencia_hash VARCHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_admin_correo ON usuario_admin (lower(correo));

-- Códigos de un solo uso enviados por correo
CREATE TABLE IF NOT EXISTS codigo_cuenta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  usuario_id INT NOT NULL REFERENCES usuario_admin (id),
  proposito VARCHAR(12) NOT NULL,
  destino VARCHAR(120) NOT NULL,
  codigo_hash VARCHAR(64) NOT NULL,
  solicitado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  expira_en TIMESTAMPTZ NOT NULL,
  intentos SMALLINT NOT NULL DEFAULT 0,
  usado_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  CHECK (proposito IN ('recuperar', 'cambiar', 'correo', 'usuario', 'recordar'))
);
CREATE INDEX IF NOT EXISTS ix_codigo_cuenta_usuario_id ON codigo_cuenta (usuario_id, solicitado_en DESC);

-- Nuevos propósitos de código: cambiar el nombre de usuario y recordar el usuario por correo
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT conname FROM pg_constraint WHERE conrelid = 'codigo_cuenta'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%proposito%' LOOP
    EXECUTE format('ALTER TABLE codigo_cuenta DROP CONSTRAINT %I', r.conname);
  END LOOP;
  ALTER TABLE codigo_cuenta ADD CONSTRAINT codigo_cuenta_proposito_check CHECK (proposito IN ('recuperar', 'cambiar', 'correo', 'usuario', 'recordar'));
END $$;

-- Archivar solicitudes rechazadas, canceladas o expiradas: se ocultan del centro de solicitudes y se conservan en la base de datos
ALTER TABLE solicitud_actividad ADD COLUMN IF NOT EXISTS archivada_en TIMESTAMPTZ;

-- Eliminar productos: sin historial se borran; con ventas o pedidos se retiran del inventario y del catálogo pero se conserva el historial
ALTER TABLE producto ADD COLUMN IF NOT EXISTS eliminado_en TIMESTAMPTZ;

-- Aviso al confirmar un pedido: el mensaje queda ligado al pedido
ALTER TABLE mensaje_whatsapp ADD COLUMN IF NOT EXISTS pedido_id BIGINT;
ALTER TABLE mensaje_whatsapp DROP CONSTRAINT IF EXISTS mensaje_whatsapp_tipo_check;
ALTER TABLE mensaje_whatsapp ADD CONSTRAINT mensaje_whatsapp_tipo_check CHECK (tipo IN ('Cotización','Aviso de confirmación','Código de verificación','Confirmación de pedido'));

-- Archivos (fotos y comprobantes) guardados en la base de datos en lugar de una carpeta del servidor
CREATE TABLE IF NOT EXISTS archivo_guardado (
  clave VARCHAR(200) NOT NULL,
  tipo VARCHAR(80) NOT NULL,
  datos BYTEA NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (clave)
);

-- ---------- Versión general (sin datos de una persona o negocio concreto) ----------
-- El usuario inicial del panel pasa de «andrea» a «admin» (solo si todavía existe «andrea» y no hay un «admin»).
UPDATE usuario_admin SET usuario = 'admin'
 WHERE usuario = 'andrea' AND NOT EXISTS (SELECT 1 FROM usuario_admin WHERE usuario = 'admin');

-- El origen de una cancelación hecha por el negocio pasa de 'andrea' a 'negocio'.
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT conname FROM pg_constraint WHERE conrelid = 'solicitud_actividad'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%origen_cancelacion%' LOOP
    EXECUTE format('ALTER TABLE solicitud_actividad DROP CONSTRAINT %I', r.conname);
  END LOOP;
  UPDATE solicitud_actividad SET origen_cancelacion = 'negocio' WHERE origen_cancelacion = 'andrea';
  ALTER TABLE solicitud_actividad ADD CONSTRAINT solicitud_actividad_origen_cancelacion_check CHECK (origen_cancelacion IS NULL OR origen_cancelacion IN ('clienta','negocio'));
END $$;

