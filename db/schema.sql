  archivo_url VARCHAR(255) NOT NULL,
  subido_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE cotizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  solicitud_id BIGINT NOT NULL,
  precio_total NUMERIC(10,2) NOT NULL,
  anticipo NUMERIC(10,2) NOT NULL,
  saldo NUMERIC(10,2) NOT NULL,
  duracion_min INT NOT NULL,
  traslado_min INT,
  vigente BOOLEAN NOT NULL DEFAULT true,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CHECK (anticipo = round(precio_total * 0.10, 2) AND saldo = precio_total - anticipo),
  CHECK (precio_total > 0),
  CHECK (duracion_min > 0)
);

CREATE TABLE actividad_agenda (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  solicitud_id BIGINT,
  sesion_id BIGINT UNIQUE,
  inicio TIMESTAMPTZ NOT NULL,
  fin TIMESTAMPTZ NOT NULL,
  estado VARCHAR(12) NOT NULL,
  confirmado_en TIMESTAMPTZ,
  PRIMARY KEY (id),
  CHECK (estado IN ('Provisional', 'Confirmada', 'Liberada')),
  CONSTRAINT ex_agenda_sin_solapamiento EXCLUDE USING gist (tstzrange(inicio, fin, '[)') WITH &&) WHERE (estado IN ('Provisional','Confirmada')),
  CHECK (num_nonnulls(solicitud_id, sesion_id) = 1),
  CHECK (fin > inicio)
);

