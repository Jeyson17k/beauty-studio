  imagen_url VARCHAR(255),
  activo BOOLEAN NOT NULL DEFAULT true,
  PRIMARY KEY (id)
);

CREATE TABLE curso (
  id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion VARCHAR(300) NOT NULL,
  modalidad VARCHAR(10) NOT NULL,
  duracion_min INT NOT NULL,
  precio_base NUMERIC(10,2),
  activo BOOLEAN NOT NULL DEFAULT true,
  PRIMARY KEY (id),
  CHECK (modalidad IN ('individual','grupal'))
);

CREATE TABLE sesion_curso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  curso_id INT NOT NULL,
  inicio TIMESTAMPTZ NOT NULL,
  fin TIMESTAMPTZ NOT NULL,
  capacidad SMALLINT NOT NULL,
  estado VARCHAR(15) NOT NULL,
  PRIMARY KEY (id),
  CHECK (estado IN ('Programada', 'Abierta', 'Llena', 'Realizada', 'Cancelada')),
  CHECK (fin > inicio),
  CHECK (capacidad >= 1)
);

CREATE TABLE solicitud_actividad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  cliente_id UUID NOT NULL,
  tipo VARCHAR(10) NOT NULL,
  servicio_id INT,
  sesion_id BIGINT,
  inicio_solicitado TIMESTAMPTZ,
  descripcion VARCHAR(300),
  fuera_local BOOLEAN NOT NULL DEFAULT false,
  direccion VARCHAR(250),
  referencia VARCHAR(150),
  estado VARCHAR(40) NOT NULL,
  plazo_pago_hasta TIMESTAMPTZ,
  revisada_en TIMESTAMPTZ,
  motivo_cierre VARCHAR(150),
  origen_cancelacion VARCHAR(10),
  registro_directo BOOLEAN NOT NULL DEFAULT false,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CHECK (estado IN ('Pendiente de revisión', 'Cotización en envío', 'Pendiente de pago', 'Plazo vencido pendiente de revisión', 'Confirmada', 'Realizada', 'No asistida', 'Cerrada', 'Rechazada', 'Cancelada', 'Expirada')),
  CHECK ((tipo='servicio' AND servicio_id IS NOT NULL AND sesion_id IS NULL) OR (tipo='curso' AND sesion_id IS NOT NULL AND servicio_id IS NULL)),
  CHECK (NOT fuera_local OR direccion IS NOT NULL),
  CHECK (tipo IN ('servicio','curso')),
  CHECK (origen_cancelacion IS NULL OR origen_cancelacion IN ('clienta','andrea'))
);

CREATE TABLE foto_solicitud (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
